"""Run the TensileLite pytest jobs against the installed ``tensilelite`` wheel.

Used by the ``tensilelite`` and ``tensilelite-common`` jobs. The test category
handling (test_categories.yaml, markers, timeouts, workers, JUnit) is
pytest_runner.py's; this script only decides what Python code those tests import.

Two paths, chosen from the installed artifact layout under
share/hipblaslt/tensilelite/:

Installed-wheel path
    ``wheels/`` holds the ``tensilelite`` wheel and the artifact root has no
    unpacked ``tensilelite`` package. The runner:

    1. pip-installs that one wheel into this interpreter (``--no-deps``; the job
       installs the test requirements);
    2. sets ``PYTHONPATH`` to a temporary shim directory that exposes only
       rocisa, rocisa_stinkytofu_adaptor and stinkytofu from the artifact root
       (they have no distribution packaging yet), so nothing else in the
       artifact root can shadow the installed wheel;
    3. checks that ``tensilelite`` is imported from this interpreter's
       site-packages, before pytest and again inside every pytest process
       (pytest's default import mode can put the artifact root on sys.path);
    4. runs ``python -m tensilelite --help`` against the real artifact root;
    5. runs pytest_runner's configured category.

Existing path
    Otherwise (rocm-libraries pins that predate installed-wheel artifacts, or
    still unpack the wheel into the artifact root), run pytest_runner.main()
    unchanged. This is today's behaviour; it is removed once TheRock's
    rocm-libraries pin ships installed-wheel artifacts.

TheRock does not interpret the wheel's version label. rocm-libraries owns that
format, and the installed package validates it against the installed ROCm when
it is imported.

Environment variables are those of pytest_runner.py. TEST_COMPONENT must be
``tensilelite`` or ``tensilelite-common``.
"""

import logging
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import pytest_runner

logging.basicConfig(level=logging.INFO, format="%(message)s")

COMPONENTS = ("tensilelite", "tensilelite-common")
PROJECT_NAME = "tensilelite"
# Packages without distribution packaging yet, reached from the artifact root.
SHIM_PACKAGES = ("rocisa", "rocisa_stinkytofu_adaptor", "stinkytofu")
REQUIRED_SHIM_PACKAGES = ("rocisa",)
GUARD_MODULE = "_therock_tensilelite_import_guard"

# Written into the shim directory. Imported by this script (before pytest) and
# loaded into every pytest process with ``-p``.
GUARD_SOURCE = '''\
"""Fail unless tensilelite is imported from this interpreter's site-packages.

Generated by TheRock's test_tensilelite.py.
"""

import importlib.metadata
import site
import sysconfig
from pathlib import Path

_ERROR = None


def installed_roots():
    roots = {sysconfig.get_paths()[key] for key in ("purelib", "platlib")}
    roots.update(getattr(site, "getsitepackages", lambda: [])())
    if site.ENABLE_USER_SITE:
        roots.add(site.getusersitepackages())
    return sorted({Path(root).resolve() for root in roots})


def check():
    """Return (module file, distribution version) or raise RuntimeError."""
    import tensilelite

    location = Path(tensilelite.__file__).resolve()
    roots = installed_roots()
    if not any(root in location.parents for root in roots):
        raise RuntimeError(
            f"tensilelite was imported from {location}, not from the installed "
            f"wheel in this interpreter's site-packages ({[str(r) for r in roots]})"
        )
    return location, importlib.metadata.version("tensilelite")


def pytest_collection_finish(session):
    global _ERROR
    try:
        check()
    except Exception as exc:  # report any import failure as a guard failure
        _ERROR = f"{type(exc).__name__}: {exc}"


def pytest_runtest_setup(item):
    if _ERROR:
        import pytest

        pytest.fail(_ERROR, pytrace=False)


def pytest_sessionfinish(session, exitstatus):
    if _ERROR and exitstatus == 0:
        session.exitstatus = 1


if __name__ == "__main__":
    location, version = check()
    print(f"{location}\\n{version}")
'''


class TensileLiteRunnerError(RuntimeError):
    """An artifact contract failure with a user-facing diagnostic."""


def uses_installed_wheel(component_root: Path) -> bool:
    """Whether the artifact layout supports testing the installed wheel."""
    if not (component_root / "wheels").is_dir():
        logging.info(
            "No TensileLite wheels in %s; using the existing path.", component_root
        )
        return False
    if (component_root / PROJECT_NAME / "__init__.py").exists():
        logging.info(
            "The artifact root still carries an unpacked tensilelite package, "
            "which would shadow the installed wheel; using the existing path."
        )
        return False
    return True


def _project_name(wheel_name: str) -> str:
    return re.sub(r"[-_.]+", "-", wheel_name.split("-", 1)[0]).lower()


def find_tensilelite_wheel(wheels_dir: Path) -> Path:
    """Return the single tensilelite wheel, selected by project name only."""
    wheels = sorted(wheels_dir.glob("*.whl"))
    for wheel in wheels:
        if len(wheel.stem.split("-")) not in (5, 6):
            raise TensileLiteRunnerError(f"Malformed wheel filename: {wheel}")
        if _project_name(wheel.name) != PROJECT_NAME:
            raise TensileLiteRunnerError(
                f"Unexpected wheel in {wheels_dir}: {wheel.name}"
            )
    if len(wheels) != 1:
        raise TensileLiteRunnerError(
            f"Expected exactly one {PROJECT_NAME} wheel in {wheels_dir}; "
            f"found {[wheel.name for wheel in wheels]}"
        )
    return wheels[0]


def install_wheel(wheel: Path) -> None:
    """Install the artifact wheel into this interpreter."""
    command = [
        sys.executable,
        "-m",
        "pip",
        "install",
        "--force-reinstall",
        "--no-deps",
        str(wheel),
    ]
    logging.info("Installing artifact wheel: %s", wheel)
    status = subprocess.run(command, check=False).returncode
    if status != 0:
        raise TensileLiteRunnerError(
            f"pip failed with status {status} installing {wheel}"
        )


def create_shim(component_root: Path, shim_dir: Path) -> None:
    """Expose only the unpackaged native-binding packages, plus the guard."""
    for name in SHIM_PACKAGES:
        source = component_root / name
        if source.exists():
            (shim_dir / name).symlink_to(source, target_is_directory=source.is_dir())
        elif name in REQUIRED_SHIM_PACKAGES:
            raise TensileLiteRunnerError(
                f"Required package {name} not found at {source}"
            )
    (shim_dir / f"{GUARD_MODULE}.py").write_text(GUARD_SOURCE, encoding="utf-8")


def wheel_test_environment(base_env: dict[str, str], shim_dir: Path) -> dict[str, str]:
    """Return `base_env` with PYTHONPATH reset to the shim and the guard loaded."""
    env = dict(base_env)
    env["PYTHONPATH"] = str(shim_dir)
    env["PYTEST_ADDOPTS"] = " ".join(
        filter(None, [f"-p {GUARD_MODULE}", base_env.get("PYTEST_ADDOPTS", "")])
    )
    return env


def _run_python(
    args: list[str], env: dict[str, str], cwd: Path
) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, *args],
        capture_output=True,
        text=True,
        check=False,
        env=env,
        cwd=cwd,
    )


def check_installed_import(env: dict[str, str], cwd: Path) -> str:
    """Check the import location; return the installed distribution version."""
    result = _run_python(["-m", GUARD_MODULE], env, cwd)
    if result.returncode != 0:
        raise TensileLiteRunnerError(
            f"tensilelite is not imported from the installed wheel: {result.stderr.strip()}"
        )
    location, version = result.stdout.strip().splitlines()[-2:]
    logging.info("tensilelite %s imported from %s", version, location)
    return version


def check_package_help(env: dict[str, str], cwd: Path) -> None:
    """Run the installed package's CLI help against the real artifact root."""
    result = _run_python(["-m", PROJECT_NAME, "--help"], env, cwd)
    if result.returncode != 0:
        raise TensileLiteRunnerError(
            f"python -m tensilelite --help failed with status {result.returncode}: "
            f"{result.stderr.strip()}"
        )
    if "create-library" not in result.stdout:
        raise TensileLiteRunnerError(
            "python -m tensilelite --help did not describe the package commands"
        )


def run_installed_wheel(
    component_name: str, test_type: str, rocm_path: Path, component_root: Path
) -> int:
    """Install the artifact wheel and run the configured category against it."""
    wheel = find_tensilelite_wheel(component_root / "wheels")
    install_wheel(wheel)

    with tempfile.TemporaryDirectory(prefix="tensilelite-shim-") as shim:
        shim_dir = Path(shim)
        create_shim(component_root, shim_dir)
        env = wheel_test_environment(
            pytest_runner.build_environment(rocm_path, component_name), shim_dir
        )
        # Run from the shim so `python -m` cannot pick up the artifact root.
        check_installed_import(env, shim_dir)
        check_package_help(env, shim_dir)

        return pytest_runner.run_phase(
            component_name,
            test_type,
            os.getenv("AMDGPU_FAMILIES"),
            os.getenv("AMDGPU_TARGETS"),
            rocm_path,
            env,
        )


def main() -> int:
    component_name = os.getenv("TEST_COMPONENT")
    therock_bin_dir = os.getenv("THEROCK_BIN_DIR")
    if component_name not in COMPONENTS:
        logging.error(
            "TEST_COMPONENT must be one of %s; got %r", COMPONENTS, component_name
        )
        return 1
    if not therock_bin_dir:
        logging.error("THEROCK_BIN_DIR environment variable is required but not set.")
        return 1

    rocm_path = Path(therock_bin_dir).resolve().parent
    component_root = pytest_runner.resolve_component_path(component_name, rocm_path)
    if not uses_installed_wheel(component_root):
        return pytest_runner.main()

    try:
        return run_installed_wheel(
            component_name,
            pytest_runner.resolve_test_category(),
            rocm_path,
            component_root,
        )
    except TensileLiteRunnerError as exc:
        logging.error("TensileLite artifact test setup failed: %s", exc)
        return 1


if __name__ == "__main__":
    sys.exit(main())
